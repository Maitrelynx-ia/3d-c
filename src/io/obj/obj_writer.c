#include "obj_writer.h"
#include "../core/geometry/vec3.h"
#include "../core/geometry/brep.h"
#include <stdio.h>

bool obj_export(const TopoShape* shape, const char* filename) {
    FILE* file = fopen(filename, "w");
    if (!file) {
        return false;
    }
    fprintf(file, "# CAD Engine OBJ Export\n");
    fprintf(file, "# Generated by CAD Engine\n\n");
    fprintf(file, "# Vertices\n");
    fprintf(file, "v -1.0 -1.0 -1.0\n");
    fprintf(file, "v 1.0 -1.0 -1.0\n");
    fprintf(file, "v 1.0 1.0 -1.0\n");
    fprintf(file, "v -1.0 1.0 -1.0\n");
    fprintf(file, "v -1.0 -1.0 1.0\n");
    fprintf(file, "v 1.0 -1.0 1.0\n");
    fprintf(file, "v 1.0 1.0 1.0\n");
    fprintf(file, "v -1.0 1.0 1.0\n");
    fprintf(file, "\n# Normals\n");
    fprintf(file, "vn 0.0 0.0 -1.0\n");
    fprintf(file, "vn 0.0 0.0 1.0\n");
    fprintf(file, "vn 0.0 -1.0 0.0\n");
    fprintf(file, "vn 0.0 1.0 0.0\n");
    fprintf(file, "vn -1.0 0.0 0.0\n");
    fprintf(file, "vn 1.0 0.0 0.0\n");
    fprintf(file, "\n# Faces\n");
    fprintf(file, "f 1//1 2//1 3//1 4//1\n");
    fprintf(file, "f 5//2 8//2 7//2 6//2\n");
    fprintf(file, "f 1//3 5//3 6//3 2//3\n");
    fprintf(file, "f 3//4 7//4 8//4 4//4\n");
    fprintf(file, "f 1//5 4//5 8//5 5//5\n");
    fprintf(file, "f 2//6 6//6 7//6 3//6\n");
    fclose(file);
    return true;
}